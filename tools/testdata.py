def assertion(
    *,
    assertion_id: str = ASSERTION_ID,
    id_attribute: str = "ID",
    signature_xml: str = "",
    subject: str = SUBJECT,
    conditions: str = CONDITIONS,
    authn: str = AUTHN,
    attributes: str = "",
) -> str:
    return (
        f'<saml:Assertion {id_attribute}="{assertion_id}" Version="2.0" IssueInstant="{INSTANT}">'
        f"<saml:Issuer>{IDP_ENTITY}</saml:Issuer>{signature_xml}{subject}{conditions}{authn}"
        f"{attributes}</saml:Assertion>"
    )


def response(
    body: str,
    *,
    response_id: str = RESPONSE_ID,
    destination: str | None = ACS_URL,
    in_response_to: str | None = "_req-fixture",
    signature_xml: str = "",
) -> str:
    attributes = f'ID="{response_id}" Version="2.0" IssueInstant="{INSTANT}"'
    if destination is not None:
        attributes += f' Destination="{destination}"'
    if in_response_to is not None:
        attributes += f' InResponseTo="{in_response_to}"'
    return (
        f"{HEADER}\n<samlp:Response {NS} {attributes}>"
        f"<saml:Issuer>{IDP_ENTITY}</saml:Issuer>{signature_xml}"
        '<samlp:Status><samlp:StatusCode Value="urn:oasis:names:tc:SAML:2.0:status:Success"/>'
        "</samlp:Status>"
        f"{body}</samlp:Response>\n"
    )


def _tampered_certificate() -> str:
    """A self-issued certificate whose own signature has been corrupted."""
    der = bytearray(certificate_der("idp"))
    der[-1] ^= 0xFF
    return base64.b64encode(bytes(der)).decode("ascii")


