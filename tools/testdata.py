XPATH = "http://www.w3.org/TR/1999/REC-xpath-19991116"
BASE64_TRANSFORM = "http://www.w3.org/2000/09/xmldsig#base64"

FAKE_DIGEST = base64.b64encode(b"fixture-digest-not-real").decode("ascii")
FAKE_SIGNATURE = base64.b64encode(b"fixture-signature-value-not-real").decode("ascii")

ASSERTION_ID = "_a1fixture"
RESPONSE_ID = "_r1fixture"
