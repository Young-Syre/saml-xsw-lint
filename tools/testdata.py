"""Small fabricated documents, one or two findings each.

These are deliberately minimal and deliberately unsigned in the cryptographic
sense: DigestValue and SignatureValue are the base64 of readable placeholder
text. The linter never verifies a signature, so a real one would add nothing
except the impression that it had been verified.

Everything is invented. Entity ids use the reserved ``.example`` TLD.
``tests/data`` is regenerated by ``python -m tools.make_examples``.
"""

from __future__ import annotations

import base64

from .samlfixtures import certificate_b64, certificate_der

HEADER = '<?xml version="1.0" encoding="UTF-8"?>'
NS = (
    'xmlns:samlp="urn:oasis:names:tc:SAML:2.0:protocol" '
    'xmlns:saml="urn:oasis:names:tc:SAML:2.0:assertion" '
    'xmlns:ds="http://www.w3.org/2000/09/xmldsig#"'
)
EXC_C14N = "http://www.w3.org/2001/10/xml-exc-c14n#"
INCLUSIVE_C14N = "http://www.w3.org/TR/2001/REC-xml-c14n-20010315"
ENVELOPED = "http://www.w3.org/2000/09/xmldsig#enveloped-signature"
RSA_SHA256 = "http://www.w3.org/2001/04/xmldsig-more#rsa-sha256"
RSA_SHA1 = "http://www.w3.org/2000/09/xmldsig#rsa-sha1"
HMAC_SHA1 = "http://www.w3.org/2000/09/xmldsig#hmac-sha1"
SHA256 = "http://www.w3.org/2001/04/xmlenc#sha256"
